function applyDynamicLanguage(lang) {
  const dict = I18N_DICTIONARY[lang] || {};

  // 1. Update text nodes in body
  const elements = document.querySelectorAll('span, a, p, h1, h2, h3, h4, h5, label, th, button, div.sidebar-group-title, div.user-role');
  elements.forEach(el => {
    // Only translate small leaf text nodes to preserve icons and layout
    if (el.children.length === 0 && el.innerText && el.innerText.trim().length > 0) {
      if (!el.getAttribute('data-orig-text')) {
        el.setAttribute('data-orig-text', el.innerText.trim());
      }

      const origText = el.getAttribute('data-orig-text');
      if (lang === 'en') {
        el.innerText = origText;
      } else if (dict[origText]) {
        el.innerText = dict[origText];
      }
    }
  });

  // 2. Update search placeholders
  const searchInputs = document.querySelectorAll('input[type="text"], input[type="search"]');
  searchInputs.forEach(input => {
    if (input.placeholder) {
      if (!input.getAttribute('data-orig-placeholder')) {
        input.setAttribute('data-orig-placeholder', input.placeholder);
      }
      const origPH = input.getAttribute('data-orig-placeholder');
      if (lang === 'en') {
        input.placeholder = origPH;
      } else if (dict[origPH]) {
        input.placeholder = dict[origPH];
      }
    }
  });
}

// Hook setLanguage to trigger applyDynamicLanguage
const originalSetLanguage = window.setLanguage;
window.setLanguage = function(lang) {
  localStorage.setItem('portal_lang', lang);
  if (typeof updateLanguageUI === 'function') {
    updateLanguageUI(lang);
  }
  applyDynamicLanguage(lang);
  document.querySelectorAll('.lang-dropdown-menu').forEach(m => m.style.display = 'none');
};

document.addEventListener('DOMContentLoaded', function() {
  const savedLang = localStorage.getItem('portal_lang') || 'en';
  applyDynamicLanguage(savedLang);
});
